#!/bin/bash
# Скачивает логотипы банков СБП с сайта НСПК в папку магазина (сайт НСПК защищён сертификатом Минцифры, поэтому -k).
# Запуск на сервере: bash ~/desire/shop/server/get-bank-logos.sh
D="$HOME/desire/shop/site/img/banks"; mkdir -p "$D"; ok=0
for id in 100000000111 100000000004 110000000005 100000000008 100000000273 100000000001 100000000007 100000000013 100000000150 100000000259 100000000010 100000000017 100000000082 100000000025 100000000006 100000000032; do
  curl -sfk --max-time 15 -o "$D/bank$id.png" "https://qr.nspk.ru/proxyapp/logo/bank$id.png" && ok=$((ok+1)) || echo "не скачался: $id"
done
echo "Скачано логотипов: $ok из 16"
